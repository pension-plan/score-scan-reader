"""Build one coverage/notes item (copy of corpus/challenge/rhythm/_tools/rsynth/build.py, adapted):
  truth.musicxml (model -> MusicXML 4.0, XSD-validated, music21 re-parse)
  engraving.ly   (model -> LilyPond 2.24, manual beams, explicit stems, forced system breaks)
  verification   (LilyPond event dump == model; Stem/NoteHead grobs of the final layout == model;
                  printed accidentals == truth; MIDI attacks == truth; counts read from the truth ==
                  counts measured on the engraving)
  clean.pdf      (undamaged 300 dpi raster of the engraving, image-only)
  scan.pdf, scan-severe.pdf (damaged image-only PDFs, scan.py; params + seed in meta.json)
"""
from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import time
import traceback

from PIL import Image

from . import scan as S
from . import verify as V
from .counts import COUNT_RULES, all_counts
from .lily import LilyWriter
from .model import (assign_positions_and_stems, check, compute_extenders, fix_unbalanced_slurs, sanitize_ties,
                    voices_with_lyrics)
from .mxl import write_musicxml

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))   # corpus/coverage/notes
CLEAN_DPI = 300
FAMILY = 'notes'
LICENSE = 'CC0'
CC0_TEXT = ('Music composed for the OMR coverage corpus (notes family); engraving (LilyPond 2.24), truth '
            'MusicXML, rasterisation and simulated scan damage generated by corpus/coverage/notes/_tools. '
            'All of it is dedicated to the public domain under CC0 1.0 '
            '(https://creativecommons.org/publicdomain/zero/1.0/).')


def run(cmd, timeout=600):
    r = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout)
    return r.returncode, r.stdout, r.stderr


def image_only(pdf):
    rc, fonts, _ = run(['pdffonts', pdf])
    font_lines = [l for l in fonts.splitlines()[2:] if l.strip()]
    rc, imgl, _ = run(['pdfimages', '-list', pdf])
    n_imgs = len([l for l in imgl.splitlines()[2:] if l.strip()])
    rc, txt, _ = run(['pdftotext', pdf, '-'])
    rc, info, _ = run(['pdfinfo', pdf])
    pages = int(re.search(r'Pages:\s+(\d+)', info).group(1))
    return {'image_only': not font_lines and n_imgs == pages and not txt.strip(), 'fonts': font_lines,
            'images': n_imgs, 'pages': pages, 'text_chars': len(txt.strip())}


def build_item(item: dict, keep_work=False):
    t0 = time.time()
    iid = item['id']
    outdir = os.path.join(ROOT, iid)
    workdir = os.path.join(ROOT, '_work', iid)
    shutil.rmtree(workdir, ignore_errors=True)
    os.makedirs(workdir, exist_ok=True)
    os.makedirs(outdir, exist_ok=True)
    for f in os.listdir(outdir):
        os.remove(os.path.join(outdir, f))
    log = {'id': iid}
    try:
        score, layout, opts = item['make']()
        sanitize_ties(score)
        fix_unbalanced_slurs(score)
        compute_extenders(score)
        assign_positions_and_stems(score)
        check(score)
        truth = os.path.join(outdir, 'truth.musicxml')
        write_musicxml(score, truth)
        xsd = V.xsd_validate(truth)
        ly = os.path.join(workdir, 'engraving.ly')
        open(ly, 'w', encoding='utf-8').write(LilyWriter(score, layout, opts).document())
        rc, warns, err, pdf, mid, evp = V.lilypond(ly, workdir)
        if rc != 0:
            raise RuntimeError('lilypond failed: ' + err[-1500:])
        eng = V.compare_engraving(score, layout, evp)
        grobs = V.compare_grobs(score, evp)
        accs = V.compare_accidentals(score, layout, evp)
        midi = V.compare_midi(score, mid)
        m21 = V.compare_music21(score, truth)
        rc_, info, _ = run(['pdfinfo', pdf])
        vec_pages = int(re.search(r'Pages:\s+(\d+)', info).group(1))
        counts, detail = all_counts(truth, vec_pages)
        eng_counts = V.engraved_counts(score, evp)
        xc = V.crosscheck_counts(counts, eng_counts)
        log['validation'] = {'xsd': xsd, 'engraving_vs_truth': eng, 'grobs_vs_truth': grobs,
                             'accidentals_vs_truth': accs, 'midi': midi, 'music21_truth_reparse': m21,
                             'counts_truth_vs_engraving': xc, 'lilypond_warnings': warns,
                             'vector_pages': vec_pages}
        problems = []
        if not xsd['ok']:
            problems.append('xsd')
        if not eng['ok']:
            problems.append('engraving dump != truth')
        if not grobs['ok']:
            problems.append('stem/notehead grobs != truth')
        if not accs['ok']:
            problems.append('printed accidentals != truth')
        if not midi['ok']:
            problems.append('midi != truth')
        if not m21['ok']:
            problems.append('music21 reparse != truth')
        if not xc['ok']:
            problems.append('counts truth != engraving')
        if warns:
            problems.append('lilypond warnings: ' + '; '.join(warns[:5]))
        if item.get('pages') and vec_pages != item['pages']:
            problems.append(f'pages {vec_pages} != {item["pages"]}')
        for tag, want in item.get('min_counts', {}).items():
            if counts.get(tag, 0) < want:
                problems.append(f'count {tag}={counts.get(tag, 0)} < required {want}')
        if problems:
            raise RuntimeError('verification failed: ' + ' | '.join(problems) + '\n' +
                               json.dumps(log['validation'], default=str)[:8000])
        shutil.copy(ly, os.path.join(outdir, 'engraving.ly'))
        # clean raster
        pages = S.render_pages(pdf, CLEAN_DPI, workdir)
        S.save_pdf([Image.fromarray(p) for p in pages], CLEAN_DPI, os.path.join(outdir, 'clean.pdf'), fmt='png')
        clean = {'dpi': CLEAN_DPI, 'pages': len(pages), 'ops': [], 'note': 'undamaged raster render (PNG)'}
        clean.update(image_only(os.path.join(outdir, 'clean.pdf')))
        # damaged variants
        degr = {}
        for fname, Vv in item['variants'].items():
            pg = S.render_pages(pdf, Vv['dpi'], workdir)
            imgs, out_dpi, oplog = S.apply_variant(pg, Vv)
            outp = os.path.join(outdir, fname)
            fmt = Vv.get('format', 'jpeg')
            S.save_pdf(imgs, out_dpi, outp, fmt='png' if fmt in ('png', 'png1') else 'jpeg',
                       quality=Vv.get('jpeg', 75), jpeg_passes=Vv.get('jpeg_passes', 1))
            io_ = image_only(outp)
            if not io_['image_only']:
                raise RuntimeError(f'{fname} is not image-only: {io_}')
            degr[fname] = {'seed': Vv['seed'], 'level': Vv.get('level'), 'recipe': Vv.get('recipe', 'typical-office-scan'), 'render_dpi': Vv['dpi'], 'dpi': out_dpi,
                           'color': Vv.get('color', 'gray'), 'format': fmt,
                           'jpeg_quality': Vv.get('jpeg') if fmt == 'jpeg' else None,
                           'jpeg_passes': Vv.get('jpeg_passes', 1) if fmt == 'jpeg' else None,
                           'ops': Vv['ops'], 'tags': S.describe(Vv), 'output_pages': io_['pages'],
                           'pixel_size': list(imgs[0].size), 'image_mode': imgs[0].mode,
                           'bytes': os.path.getsize(outp), 'image_only_check': io_, 'op_log': oplog}
        part_names = [p.name for p in score.parts]
        exp = {'parts': part_names, 'must_not_split': item['expected']['must_not_split'],
               'staves_per_part': {p.name: p.staves for p in score.parts},
               'measures': len(score.measures), 'first_measure_number': score.measures[0].number,
               'notes': item['expected'].get('notes', '')}
        symbols = sorted(k for k in counts if not k.startswith('x-'))
        meta = {
            'id': iid, 'family': FAMILY, 'title': item['title'],
            'description': item.get('description', ''),
            'symbols': symbols,
            'focus_symbols': item.get('focus', []),
            'layout': item['layout'],
            'expected': exp,
            'counts': counts,
            'counts_detail': detail,
            'count_rules': COUNT_RULES,
            'notes': item.get('notes', []),
            'degradations': degr,
            'dpi': degr['scan.pdf']['dpi'],
            'pages': vec_pages,
            'license': LICENSE,
            'license_detail': 'CC0-1.0: composition, engraving, truth and scans created for this corpus',
            'composer': score.composer,
            'files': {'truth': 'truth.musicxml', 'engraving': 'engraving.ly', 'clean': 'clean.pdf',
                      'scan': 'scan.pdf', 'scan_severe': 'scan-severe.pdf', 'attribution': 'ATTRIBUTION.txt'},
            'clean': clean,
            'validation': {
                'truth_xsd_valid': xsd['ok'],
                'music21_reparse_matches_model': m21['ok'],
                'engraving_event_dump_matches_truth': eng['ok'],
                'engraving_events_compared': sum(v['n_expected'] for v in eng['voices'].values()),
                'stem_grobs_compared': sum(v['n_expected'] for v in grobs['stems'].values()),
                'notehead_grobs_compared': sum(v['n_expected'] for v in grobs['heads'].values()),
                'printed_accidentals_compared': accs['n_expected'],
                'time_signatures_compared': sum(v['n_expected'] for v in eng['timesig'].values()),
                'midi_attacks_match_truth': midi['ok'], 'midi_attacks': midi['expected_attacks'],
                'midi_grace_notes_excluded': midi['grace_notes'],
                'counts_truth_equal_engraving': xc['ok'],
                'engraved_counts': eng_counts,
                'lilypond_warnings': warns,
                'method': 'LilyPond 2.24 run with an instrumented dump (nsynth/dump.ly): every note/rest event '
                          '(onset, pitch, notated type, dots, tuplet scale, grace offset), tie, beam start/stop, '
                          'slur, tremolo, time signature, bar number/measure position; every Stem of the final '
                          'layout (direction, duration log, beamed, beams/beamlets left and right, stem-tremolo '
                          'strokes, heads) and every NoteHead (staff position -> ledger lines, head type, font '
                          'size for grace/cue); every printed accidental. All compared with the model the truth '
                          'is written from; plus LilyPond MIDI attacks, a music21 re-parse of truth.musicxml and '
                          'xmllint against MusicXML 4.0 XSD. The symbol counts in this file are read back from '
                          'truth.musicxml (nsynth/counts.py) and must equal the counts measured on the engraving.',
            },
            'generator': 'corpus/coverage/notes/_tools/run_all.py (nsynth/items.py, build.py, scan.py)',
        }
        with open(os.path.join(outdir, 'meta.json'), 'w') as f:
            json.dump(meta, f, indent=2, default=str, ensure_ascii=False)
        with open(os.path.join(outdir, 'ATTRIBUTION.txt'), 'w') as f:
            f.write(f'{item["title"]}\n\n{item.get("attribution", "")}\n{CC0_TEXT}\n')
        log['ok'] = True
        log['meta'] = meta
    except Exception as e:
        log['ok'] = False
        log['error'] = repr(e)[:8000]
        log['trace'] = traceback.format_exc()[-4000:]
    log['seconds'] = round(time.time() - t0, 1)
    if not keep_work and log.get('ok'):
        shutil.rmtree(workdir, ignore_errors=True)
    return log
