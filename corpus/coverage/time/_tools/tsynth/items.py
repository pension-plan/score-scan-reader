"""Coverage suite, family 'time': nine short pieces composed for this corpus (CC0 1.0).
Text of t04 public domain (William Blake, 1794).  Each make() -> (score, layout, opts).

DSL: absolute LilyPond pitch (c' = C4), sticky durations, '|' bar lines, \\time n/d[:common|:cut]
in the first voice, \\tuplet a/n { } (may nest), ~ ties (<c'~ e'> partial chord tie), [ ] beams.
"""
from __future__ import annotations

from .model import set_verses
from .rdsl import build_score

CC0 = ('Music composed for the OMR coverage suite (family "time"); engraving (LilyPond 2.24), truth '
       'MusicXML, rasterisation and simulated scan damage generated by corpus/coverage/time/_tools. '
       'All of it is dedicated to the public domain under CC0 1.0 '
       '(https://creativecommons.org/publicdomain/zero/1.0/).')
COMPOSER = 'OMR coverage suite (CC0)'


def single_layout(pid, name, short=None, clef='treble', verses=(), vkeys=('1',)):
    st = {'id': f'st{pid}', 'clef': clef, 'name': name, 'voices': [(pid, k) for k in vkeys], 'lyrics': []}
    if short:
        st['short'] = short
    if verses:
        st['lyrics'] = [{'voice': (pid, vkeys[0]), 'verses': list(verses), 'place': 'below'}]
    return {'type': None, 'staves': [st]}


def piano_group(pid, name, rh=('1',), lh=('5',), short=None):
    g = {'type': 'PianoStaff', 'name': name,
         'staves': [{'id': f'st{pid}s1', 'clef': 'treble', 'voices': [(pid, k) for k in rh], 'lyrics': []},
                    {'id': f'st{pid}s2', 'clef': 'bass', 'voices': [(pid, k) for k in lh], 'lyrics': []}]}
    if short:
        g['short'] = short
    return g


def opts_for(title, subtitle=None, composer=COMPOSER, poet=None, staff_size=20, extra_paper=(), extra_layout=()):
    hdr = {'title': title, 'composer': composer}
    if subtitle:
        hdr['subtitle'] = subtitle
    if poet:
        hdr['poet'] = poet
    return {'header': hdr, 'staff_size': staff_size, 'paper': 'a4',
            'paper_extra': list(extra_paper), 'layout_extra': list(extra_layout)}


def melody(pid, name, abbr, music, systems, pages=None, title='', clef='treble', key=None, lyricist='',
           instrument='other'):
    spec = dict(title=title, composer=COMPOSER, lyricist=lyricist, rights='CC0 1.0',
                parts=[dict(id=pid, name=name, abbr=abbr, instrument=instrument, clefs=[clef],
                            voices=[dict(key='1', music=music)])],
                systems=systems, pages=pages or [len(systems)])
    if key:
        spec['key'] = key
    return build_score(spec)


