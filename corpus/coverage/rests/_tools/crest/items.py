"""coverage/rests items: short pieces composed for this corpus (CC0 1.0), each concentrating one
group of rest symbols.  make() -> (score, layout, opts).

DSL (rdsl.py, absolute LilyPond pitches): r4 = rest at its normal position, d''4\\rest or r4\\at=d''
= rest drawn at the staff position of d'' (used for every rest in a two-voice measure), R = whole-bar
rest, R*n = multi-bar rest (church-rest symbols up to 10 bars, H-bar beyond; R*n:h forces the H-bar),
R\\at=g' = whole-bar rest at the staff position of g'."""
from __future__ import annotations

from .rdsl import build_score

CC0 = ('Music composed for the OMR coverage corpus (rests family); engraving (LilyPond 2.24), truth MusicXML, '
       'rasterisation and simulated scan damage generated by corpus/coverage/rests/_tools. '
       'All of it is dedicated to the public domain under CC0 1.0 '
       '(https://creativecommons.org/publicdomain/zero/1.0/).')
COMPOSER = 'OMR coverage corpus (CC0)'


def single_layout(pid, name, short=None, clef='treble', vkeys=('1',)):
    st = {'id': f'st{pid}', 'clef': clef, 'name': name, 'voices': [(pid, k) for k in vkeys], 'lyrics': []}
    if short:
        st['short'] = short
    return {'type': None, 'staves': [st]}


def piano_group(pid, name, rh=('1',), lh=('5',), short=None):
    g = {'type': 'PianoStaff', 'name': name,
         'staves': [{'id': f'st{pid}s1', 'clef': 'treble', 'voices': [(pid, k) for k in rh], 'lyrics': []},
                    {'id': f'st{pid}s2', 'clef': 'bass', 'voices': [(pid, k) for k in lh], 'lyrics': []}]}
    if short:
        g['short'] = short
    return g


def opts_for(title, subtitle=None, composer=COMPOSER, staff_size=20, extra_paper=(), extra_layout=()):
    hdr = {'title': title, 'composer': composer}
    if subtitle:
        hdr['subtitle'] = subtitle
    return {'header': hdr, 'staff_size': staff_size, 'paper': 'a4',
            'paper_extra': list(extra_paper), 'layout_extra': list(extra_layout)}


def solo(spec_music, pid, name, abbr, title, subtitle, systems, clef='treble', staff_size=20, key=None,
         extra_paper=()):
    spec = dict(title=title, composer=COMPOSER, rights='CC0 1.0',
                parts=[dict(id=pid, name=name, abbr=abbr, instrument='other', clefs=[clef],
                            voices=[dict(key='1', music=spec_music)])],
                systems=systems, pages=[len(systems)])
    if key:
        spec['key'] = key
    sc = build_score(spec)
    lay = {'groups': [single_layout(pid, name, clef=clef)]}
    return sc, lay, opts_for(title, subtitle, staff_size=staff_size, extra_paper=extra_paper)


