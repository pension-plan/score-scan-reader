// node tools/textglyphs.js > src/textglyphs.js
// Letter and chord-symbol glyph templates (src/text.js readMarkByShape, chordByShape) from the
// synthetic LilyPond pages in work/glyphsynth (made by work/glyphsynth/gen.py): rehearsal letters
// A-Z in boxes and circles, and a chord-symbol set, each page in one text font. Training fonts:
// C059, Nimbus Roman, Nimbus Sans; Liberation Serif and DejaVu Sans pages are held out for testing.
// Each glyph: [char, width / height, 120 digits (10 x 12 cells of ink share, 0-9)].
const path = require('path');
const { readGray } = require('../src/image');
const omr = require('../src/omr');
const { pageMarks } = require('../src/symbols');
const T = require('../src/text');
const { _glyphImage: glyphImage } = require('../src/assemble');
const DIR = path.join(__dirname, '../work/glyphsynth');
const FONTS = (process.env.FONTS || 'c059,nimbusroman,nimbussans').split(',');
const LET = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ';
// what each chord of gen.py's CHORDS prints, glyph by glyph
const CHORD_TEXT = ['C', 'Cm', 'C7', 'Cm7', 'CΔ', 'C6', 'Cm6', 'C9', 'Csus4', 'C°', 'C°7', 'Cø', 'C+',
  'D', 'Dm', 'D7', 'Em7', 'F', 'FΔ', 'G7', 'Gsus4', 'Am', 'Am7', 'Bø', 'B°7',
  'B♭', 'B♭7', 'E♭Δ', 'A♭', 'F♯m', 'C♯m7', 'D♭9', 'G♭6', 'C/E', 'G/B', 'F/A', 'Dm/F', 'A7/C♯',
  'E+', 'Asus2', 'Gm6', 'Cm9', 'F9', 'E7', 'B7', 'DΔ'].map(t => [...t]);
const enc = (g) => Array.from(g, v => Math.max(0, Math.min(9, Math.round(v * 9)))).join('');
(async () => {
  const marks = [], chords = [];
  for (const f of FONTS.concat(['default'])) {
    if (f === 'default') { await chordPage(f); continue; }
    for (const kind of ['box', 'circle']) {
      const c = omr.createConverter({});
      const e = await c.addPage(readGray(path.join(DIR, `marks-${kind}-${f}-1.pgm`)), 0, 1);
      const m = pageMarks(e.fr, e.asm);
      const rs = m.rehearsals.filter(r => !m.rehearsals.some(q => q !== r && q.box[0] <= r.box[0] && q.box[1] <= r.box[1] && q.box[2] >= r.box[2] && q.box[3] >= r.box[3]))
        .sort((a, b) => a.sys - b.sys || a.x - b.x);
      console.error(`marks-${kind}-${f}: ${rs.length} marks`);
      // all 26 found: the k-th in page order is the k-th letter (pages with marks missed are skipped)
      if (rs.length !== 26) continue;
      rs.forEach((r, k) => {
        const comp = e.asm.comps.find(q => q.x0 === r.box[0] && q.y0 === r.box[1] && q.x1 === r.box[2] && q.y1 === r.box[3]);
        const ig = T._inkGrid(T._markInterior(e.fr.R, comp, kind === 'circle'));
        if (ig) marks.push([LET[k], +ig.asp.toFixed(3), enc(ig.g)]);
      });
    }
    {
      // rehearsal digits 1-9, 0 in boxes
      const c = omr.createConverter({});
      const e = await c.addPage(readGray(path.join(DIR, `digits-box-${f}-1.pgm`)), 0, 1);
      const m = pageMarks(e.fr, e.asm);
      const rs = m.rehearsals.filter(r => !m.rehearsals.some(q => q !== r && q.box[0] <= r.box[0] && q.box[1] <= r.box[1] && q.box[2] >= r.box[2] && q.box[3] >= r.box[3]))
        .sort((a, b) => a.sys - b.sys || a.x - b.x);
      console.error(`digits-box-${f}: ${rs.length} marks`);
      if (rs.length === 10) rs.forEach((r, k) => {
        const comp = e.asm.comps.find(q => q.x0 === r.box[0] && q.y0 === r.box[1] && q.x1 === r.box[2] && q.y1 === r.box[3]);
        const ig = T._inkGrid(T._markInterior(e.fr.R, comp, false));
        if (ig) marks.push(['1234567890'[k], +ig.asp.toFixed(3), enc(ig.g)]);
      });
    }
    await chordPage(f);
  }
  async function chordPage(f) {
    const c = omr.createConverter({});
    const e = await c.addPage(readGray(path.join(DIR, `chords-${f}-1.pgm`)), 0, 1);
    const sp = e.fr.ss;
    let k = 0, ok = 0;
    for (const sy of e.asm.systems) {
      const st = sy.staves[0].st;
      for (const [xa, xb] of sy.measures) {
        const top = st.yAt(0, xa);
        const cs = e.asm.comps.filter(q => q.area >= 4 && q.y1 < top - 0.3 * sp && q.y0 > top - 5 * sp && q.x0 >= xa - 0.3 * sp && q.x0 < xb - 0.5 * sp).sort((a, b) => a.x0 - b.x0);
        const want = CHORD_TEXT[k++];
        if (!want || cs.length !== want.length) { console.error(`chords-${f} #${k}: ${cs.length} glyphs for ${want}`); continue; }
        ok++;
        cs.forEach((q, i) => { const ig = T._inkGrid(glyphImage(e.fr.R, q)); if (ig) chords.push([want[i], +ig.asp.toFixed(3), enc(ig.g), +((q.y1 - q.y0 + 1) / sp).toFixed(2)]); });
      }
    }
    console.error(`chords-${f}: ${ok} of ${k} chords harvested`);
  }
  console.log(`'use strict';
// Letter and chord-symbol glyph templates for src/text.js, generated by tools/textglyphs.js
// (do not edit by hand): marks [char, width/height, 10x12 ink grid as digits 0-9];
// chords the same plus the glyph height in staff spaces.
module.exports = {
  marks: [
${marks.map(m => '    ' + JSON.stringify(m) + ',').join('\n')}
  ],
  chords: [
${chords.map(m => '    ' + JSON.stringify(m) + ',').join('\n')}
  ],
};`);
})();
