// node tools/digitglyphs.js > src/digitglyphs.js
// Builds the bar-number digit templates (src/text.js readDigits) from the coverage corpus'
// clean pages: every text line text.js marks as a bar number is read by OCR (tesseract,
// the lyrics setup); a line whose digits match its glyphs one to one gives one sample per
// glyph. Samples of a digit are averaged on a grid of ~0.12 staff space and sized in staff
// spaces (median). Needs spike/ocr/node_modules/tesseract.js; offline only.
const fs = require('fs'), path = require('path');
const { readGray } = require('../src/image');
const omr = require('../src/omr');
const { pageMarks } = require('../src/symbols');
const { _glyphImage: glyphImage } = require('../src/assemble');
const { _gridOf: gridOf, _lineCrop: lineCrop } = require('../src/text');
const CACHE = path.join(__dirname, '../work/cache');
const CELL = 0.12, GW = 8, GH = 12;
(async () => {
  const { createWorker } = require(path.join(__dirname, '../../spike/ocr/node_modules/tesseract.js'));
  const { PNG } = require('pngjs');
  const worker = await createWorker('eng', 1, { langPath: path.join(__dirname, '../dist/assets'), gzip: true, cacheMethod: 'none' });
  await worker.setParameters({ tessedit_pageseg_mode: '7', user_defined_dpi: '300', tessedit_char_whitelist: '0123456789' });
  const ocr = async (img) => {
    const png = new PNG({ width: img.width, height: img.height });
    for (let i = 0; i < img.data.length; i++) { png.data[i * 4] = png.data[i * 4 + 1] = png.data[i * 4 + 2] = img.data[i]; png.data[i * 4 + 3] = 255; }
    const { data } = await worker.recognize(PNG.sync.write(png));
    return { text: data.text.trim(), conf: data.confidence };
  };
  const samples = {};
  const dirs = fs.readdirSync(CACHE).filter(d => /^coverage__.*__clean__r200$/.test(d));
  for (const d of dirs) {
    for (const f of fs.readdirSync(path.join(CACHE, d)).filter(f => /^p-\d+\.pgm$/.test(f))) {
      const c = omr.createConverter({});
      const e = await c.addPage(readGray(path.join(CACHE, d, f)), 0, 1);
      if (!e) continue;
      const m = pageMarks(e.fr, e.asm), sp = e.fr.ss;
      for (const t of m.text.filter(t => t.role === 'measure')) {
        const r = await ocr(lineCrop(e.fr, t.box, t.h));
        const comps = t.comps.slice().sort((a, b) => a.x0 - b.x0);
        if (!/^\d+$/.test(r.text) || r.conf < 70 || r.text.length !== comps.length) continue;
        comps.forEach((cc, k) => {
          const g = gridOf(glyphImage(e.fr.R, cc), GH, GW);
          (samples[r.text[k]] ||= []).push({ g, w: (cc.x1 - cc.x0 + 1) / sp, h: (cc.y1 - cc.y0 + 1) / sp });
        });
      }
    }
  }
  await worker.terminate();
  const med = (a) => { const s = a.slice().sort((x, y) => x - y); return s[s.length >> 1]; };
  const out = [];
  for (const dg of Object.keys(samples).sort()) {
    const S = samples[dg];
    const rows = [];
    for (let y = 0; y < GH; y++) { let r = ''; for (let x = 0; x < GW; x++) r += S.reduce((a, s) => a + s.g[y * GW + x], 0) / S.length >= 0.45 ? '#' : '.'; rows.push(r); }
    out.push(`  [${JSON.stringify(dg)}, ${med(S.map(s => s.w)).toFixed(2)}, ${med(S.map(s => s.h)).toFixed(2)}, [\n${rows.map(r => `    '${r}',`).join('\n')}\n  ]], // ${S.length} samples`);
    console.error(dg, S.length);
  }
  console.log(`'use strict';
// Bar-number digit templates for src/text.js, generated by tools/digitglyphs.js
// (do not edit by hand): [digit, width, height (staff spaces), grid rows].
module.exports = [
${out.join('\n')}
];`);
})();
