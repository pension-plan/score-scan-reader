// node tools/dynglyphs.js > src/dynglyphs.js
// Builds the dynamics letter templates (src/text.js) from engraved pages of the
// coverage corpus: each sample is a page raster, a point inside the glyph's
// component and its text. The glyph is cut from the staff-removed page (fr.R),
// sized in staff spaces and drawn on a grid of cells ~0.2 staff space.
const path = require('path');
const { readGray } = require('../src/image');
const { front } = require('../src/front');
const { labelComponents } = require('../src/cc');
const { _glyphImage: glyphImage } = require('../src/assemble');
const { _gridOf: gridOf } = require('../src/text');
const C = (id) => path.join(__dirname, '../work/cache', id, 'p-1.pgm');
const MK03 = C('coverage__marks__mk03-dynamics-hairpins-cello__clean__r200');
// [page, x, y (top-left of the glyph box), text]
const SAMPLES = [
  [MK03, 588, 561, 'f'], [MK03, 658, 228, 'p'], [MK03, 976, 571, 'm'], [MK03, 583, 571, 's'], [MK03, 196, 738, 'z'],
  [MK03, 1215, 395, 'ff'], [MK03, 1347, 561, 'fff'], [MK03, 317, 246, 'pp'], [MK03, 1317, 727, 'ppp'], [MK03, 170, 570, 'fp'],
];
const CELL = 0.12;
const pages = new Map();
const out = [];
for (const [pg, x, y, text] of SAMPLES) {
  if (!pages.has(pg)) {
    const fr = front(readGray(pg));
    pages.set(pg, { fr, comps: labelComponents(fr.R).comps });
  }
  const { fr, comps } = pages.get(pg);
  const c = comps.filter(c => Math.abs(c.x0 - x) <= 2 && Math.abs(c.y0 - y) <= 2).sort((a, b) => b.area - a.area)[0];
  if (!c) { console.error('no glyph at', x, y, text); continue; }
  const sp = fr.ss, w = (c.x1 - c.x0 + 1) / sp, h = (c.y1 - c.y0 + 1) / sp;
  const gw = Math.max(4, Math.round(w / CELL)), gh = Math.max(4, Math.round(h / CELL));
  const g = gridOf(glyphImage(fr.R, c), gh, gw);
  const rows = [];
  for (let r = 0; r < gh; r++) { let s = ''; for (let k = 0; k < gw; k++) s += g[r * gw + k] >= 0.35 ? '#' : '.'; rows.push(s); }
  out.push(`  [${JSON.stringify(text)}, ${w.toFixed(2)}, ${h.toFixed(2)}, [\n${rows.map(r => `    '${r}',`).join('\n')}\n  ]],`);
}
console.log(`'use strict';
// Dynamics letter templates for src/text.js, generated by tools/dynglyphs.js
// (do not edit by hand): [text, width, height (staff spaces), grid rows].
module.exports = [
${out.join('\n')}
];`);
